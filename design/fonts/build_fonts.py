#!/usr/bin/env python3
"""Builds the whole LynkOmni font system from design/fonts/scripts.v1.json and the official font files.

Run:  python3 design/fonts/build_fonts.py --source-root <checkout of github.com/google/fonts> --upstream-commit <sha>
      python3 design/fonts/build_fonts.py --css-only     (re-writes fonts.css and the TypeScript table, no font sources needed)

Writes:
  design/fonts/<family>-<subset>.woff2   one file per family and script group, so a page downloads only the scripts it shows
  design/fonts/LICENSES/<family>-OFL.txt the SIL Open Font License of each family
  design/fonts/sources.json              exact inputs (commit, SHA-256) and outputs, so anyone can rebuild the same files
  design/fonts.css                       @font-face rules with unicode ranges, plus right-to-left and script spacing rules
  ts/src/fonts.generated.ts              languages, directions and files per script for the apps (offline precache)

Per family: keep only the weights we use, pin other axes (width 100, Inter's optical size at text size), keep every
OpenType layout feature (Arabic joining and Devanagari conjuncts need them), cut by unicode range, compress to WOFF2.
When the Python brotli package is missing, Node's built-in Brotli encoder is used instead."""
import argparse, hashlib, io, json, os, re, shutil, subprocess, sys, types

HERE = os.path.dirname(os.path.abspath(__file__))
DESIGN = os.path.dirname(HERE)
ROOT = os.path.dirname(DESIGN)
REG_PATH = os.path.join(HERE, "scripts.v1.json")
CSS_PATH = os.path.join(DESIGN, "fonts.css")
TS_PATH = os.path.join(ROOT, "ts", "src", "fonts.generated.ts")


def registry():
    with open(REG_PATH, encoding="utf-8") as f:
        return json.load(f)


def _node_brotli():
    """A stand-in for the brotli module (only what fontTools uses), backed by Node's zlib."""
    js_c = ("const z=require('zlib');const c=[];process.stdin.on('data',d=>c.push(d)).on('end',()=>{const b=Buffer.concat(c);"
            "process.stdout.write(z.brotliCompressSync(b,{params:{[z.constants.BROTLI_PARAM_MODE]:+process.argv[1],"
            "[z.constants.BROTLI_PARAM_QUALITY]:+process.argv[2],[z.constants.BROTLI_PARAM_SIZE_HINT]:b.length}}))})")
    js_d = "const z=require('zlib');const c=[];process.stdin.on('data',d=>c.push(d)).on('end',()=>process.stdout.write(z.brotliDecompressSync(Buffer.concat(c))))"
    m = types.ModuleType("brotli")
    m.MODE_GENERIC, m.MODE_TEXT, m.MODE_FONT = 0, 1, 2
    m.compress = lambda data, mode=0, quality=11, lgwin=22, lgblock=0: subprocess.run(["node", "-e", js_c, str(mode), str(quality)], input=data, capture_output=True, check=True).stdout
    m.decompress = lambda data: subprocess.run(["node", "-e", js_d], input=data, capture_output=True, check=True).stdout
    m.error = Exception
    return m


try:
    import brotli  # noqa: F401
except ImportError:
    sys.modules["brotli"] = _node_brotli()


def codepoints(rng):
    out = []
    for a, b in re.findall(r"U\+([0-9A-Fa-f]+)(?:-([0-9A-Fa-f]+))?", rng):
        lo = int(a, 16); out.extend(range(lo, (int(b, 16) if b else lo) + 1))
    return out


def faces(reg):
    """(family key, subset, unicode-range, script) for every file, without duplicates, in a stable order."""
    seen, out = set(), []
    for sname, s in reg["scripts"].items():
        for sub, rng in s["subsets"].items():
            for fam in dict.fromkeys([s["body"], s["heading"]]):
                if (fam, sub) not in seen:
                    seen.add((fam, sub)); out.append((fam, sub, rng, sname))
    return out


def filename(fam, sub):
    return f"{fam}-{sub}.woff2"


def langs_of(reg, pred):
    return [k for k, v in reg["languages"].items() if pred(reg["scripts"][v["script"]])]


def write_css(reg):
    lines = ["/* GENERATED by design/fonts/build_fonts.py from design/fonts/scripts.v1.json. Do not edit by hand.",
             "   LynkOmni fonts, SELF-HOSTED and bundled in every app so text works offline. No third-party font link anywhere.",
             "   Montserrat and Inter for Latin, Cyrillic, Greek and Vietnamese; Noto Kufi Arabic and Noto Sans Arabic for Arabic-script",
             "   languages; Noto Sans Hebrew; Noto Sans Devanagari. Each file covers one script group (unicode-range), so a page downloads",
             "   only what it shows. Preload the two Latin files:  <link rel=\"preload\" href=\"/fonts/inter-latin.woff2\" as=\"font\" type=\"font/woff2\" crossorigin> */"]
    for fam, sub, rng, _ in faces(reg):
        F = reg["families"][fam]
        lines.append(f"@font-face {{ font-family: '{F['name']}'; font-style: normal; font-weight: {F['weight']}; font-display: swap; src: url('/fonts/{filename(fam, sub)}') format('woff2'); unicode-range: {rng}; }}")
    rtl = langs_of(reg, lambda s: s["dir"] == "rtl")
    lines.append("/* Right-to-left languages. Apps set <html lang=\"..\" dir=\"rtl\"> (ts/src/fonts.ts direction()); these rules are the fallback. Use logical CSS (margin-inline-start, not margin-left). */")
    lines.append(", ".join(f":root:lang({l})" for l in rtl) + " { direction: rtl; }")
    for sname, s in reg["scripts"].items():
        ls = [k for k, v in reg["languages"].items() if v["script"] == sname]
        if not ls:
            continue
        sel = ", ".join(f":lang({l})" for l in ls)
        if s.get("line_height"):
            lines.append(f"/* {sname}: taller letters need more space between lines */")
            lines.append(f"{sel} {{ line-height: {s['line_height']}; }}")
        if s.get("cursive"):
            lines.append(f"/* {sname}: letters join, so spacing or capitals would break words */")
            lines.append(", ".join(f"{q} :is(h1, h2, h3, h4, h5, h6, .font-heading, .badge-label, .micro-chip)" for q in (f":lang({l})" for l in ls)) + " { letter-spacing: 0; text-transform: none; }")
    lines.append("/* Scripts not listed in design/fonts/scripts.v1.json fall through to the device's own font for that script. */")
    with open(CSS_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def write_ts(reg):
    langs = {k: {"name": v["name"], "native": v["native"], "script": v["script"], "dir": reg["scripts"][v["script"]]["dir"]} for k, v in reg["languages"].items()}
    files = {}
    for fam, sub, _, sname in faces(reg):
        files.setdefault(sname, []).append(filename(fam, sub))
    first = [f for s, v in reg["scripts"].items() if v.get("first_load") for f in files[s] if f.endswith("-latin.woff2")]
    body = ("// GENERATED by design/fonts/build_fonts.py from design/fonts/scripts.v1.json. Do not edit by hand.\n"
            f"export const LANGUAGES: Record<string, {{ name: string; native: string; script: string; dir: \"ltr\" | \"rtl\" }}> = {json.dumps(langs, ensure_ascii=False, indent=1)};\n"
            f"export const SCRIPT_FILES: Record<string, string[]> = {json.dumps(files, indent=1)};\n"
            f"export const FIRST_LOAD: string[] = {json.dumps(first)};\n")
    with open(TS_PATH, "w", encoding="utf-8") as f:
        f.write(body)


def sha(p):
    with open(p, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def build_fonts(reg, root):
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer
    from fontTools import subset
    made, inputs = {}, {}
    cache = {}
    for fam, sub, rng, _ in faces(reg):
        F = reg["families"][fam]
        src = os.path.join(root, F["source"])
        if fam not in cache:
            base = TTFont(src)
            axes = {k: (tuple(v) if isinstance(v, list) else v) for k, v in F["axes"].items()}
            base = instancer.instantiateVariableFont(base, axes)    # a pair narrows an axis, a number pins it
            buf = io.BytesIO(); base.save(buf); cache[fam] = buf.getvalue()
            inputs[fam] = {"path": F["source"], "sha256": sha(src), "axes_kept": F["axes"]}
            os.makedirs(os.path.join(HERE, "LICENSES"), exist_ok=True)
            shutil.copyfile(os.path.join(root, F["licence"]), os.path.join(HERE, "LICENSES", f"{fam}-OFL.txt"))
        font = TTFont(io.BytesIO(cache[fam]))
        o = subset.Options()
        o.flavor = "woff2"
        o.layout_features = F.get("features", ["*"])   # complex scripts keep every shaping feature (joining, marks, conjuncts); Latin keeps a short list
        o.layout_scripts = ["*"]
        o.name_IDs = ["*"]; o.name_languages = ["*"]   # keep copyright and licence notices (OFL)
        o.notdef_outline = True
        o.hinting = False               # phone browsers ignore TrueType hints; dropping them keeps files small
        s = subset.Subsetter(o)
        s.populate(unicodes=codepoints(rng))
        s.subset(font)
        out = io.BytesIO(); font.flavor = "woff2"; font.save(out)
        p = os.path.join(HERE, filename(fam, sub))
        with open(p, "wb") as f:
            f.write(out.getvalue())
        made[filename(fam, sub)] = len(out.getvalue())
    for old in os.listdir(HERE):        # remove files no longer named by the registry
        if old.endswith(".woff2") and old not in made:
            os.remove(os.path.join(HERE, old))
    return made, inputs


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--source-root"); ap.add_argument("--upstream-commit", default=""); ap.add_argument("--css-only", action="store_true")
    a = ap.parse_args(argv)
    reg = registry()
    write_css(reg); write_ts(reg)
    if a.css_only:
        print("wrote design/fonts.css and ts/src/fonts.generated.ts"); return
    made, inputs = build_fonts(reg, a.source_root)
    rec = {"source": reg["source"]["repository"], "licence": reg["source"]["licence"] + " (see LICENSES/)", "upstream_commit": a.upstream_commit,
           "inputs": inputs, "outputs": {f: {"bytes": made[f], "sha256": sha(os.path.join(HERE, f))} for f in sorted(made)}}
    with open(os.path.join(HERE, "sources.json"), "w", encoding="utf-8") as f:
        json.dump(rec, f, indent=1); f.write("\n")
    for f in sorted(made):
        print(f"{f}: {made[f] / 1024:.1f} KB")


if __name__ == "__main__":
    main(sys.argv[1:])
