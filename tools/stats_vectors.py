#!/usr/bin/env python3
"""Shared vectors for LynkStat's additions (SERVICES UPDATE, master blueprint 67.5): core/stats.py is the reference and
ts/src/stats.ts must agree. Also writes ts/src/stats.generated.ts.
  python3 tools/stats_vectors.py          writes contract/vectors/stats.v1.json and ts/src/stats.generated.ts
  python3 tools/stats_vectors.py --check  fails when either file is out of date (tests/test_stats.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import stats as S  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "stats.v1.json")
TS = os.path.join(ROOT, "ts", "src", "stats.generated.ts")


def _try(f, *a):
    try:
        return {"value": f(*a)}
    except ValueError:
        return {"error": True}


def build():
    buys = [{"customer": "a", "month": "2026-01"}, {"customer": "a", "month": "2026-02"}, {"customer": "b", "month": "2026-01"},
            {"customer": "b", "month": "2026-04"}, {"customer": "c", "month": "2026-02"}, {"customer": "c", "month": "2026-03"},
            {"customer": "d", "month": "2025-12"}, {"customer": "a", "month": "2025-12"}, {"customer": "e", "month": "2026-04"}]
    base = {"units": 1000, "price_minor": 2500, "unit_cost_minor": 1400, "staff_minor": 300000}
    changes = [{}, {"price_bp": 1000}, {"price_bp": -1500, "cost_bp": 500}, {"staff_hours_bp": -2000}, {"price_bp": 333, "cost_bp": -77, "staff_hours_bp": 1}, {"price_bp": 20000}]
    figs = {"sales": 1250000, "refunds": 25000, "cost_of_sales": 700000, "orders": 340, "customers": 0, "visits": -3}
    exprs = ["sales - refunds", "(sales - refunds - cost_of_sales) * 10000 / sales", "sales / orders", "sales / customers", "-sales / 7",
             "sales / visits", "2 * (orders + 1) / 3", "sales*sales*sales", "sales +", "(sales", "sales; drop", "profit", "", "10000/3*3",
             "sales / (orders - 340)", "  orders   *  2 ", "1+" * 20 + "1", "5 - -2", "sales / orders ** 2", "sales / 0 )", "sales ** 2"]
    rows = [{"branch": "kigali", "v": 1}, {"branch": "huye", "v": 2}, {"branch": None, "v": 3}]
    return {"version": 1, "description": "LynkStat's additions (SERVICES UPDATE 67.5). core/stats.py is the reference.",
            "cohorts": [{"buys": b, "expect": S.cohorts(b)} for b in (buys, [], buys[:1])],
            "what_if": [{"base": base, "changes": c, "e": e, "expect": S.what_if(base, c, e)} for c in changes for e in (None, -5000, 0)],
            "measures": [{"expr": x, "names": _try(S.measure_names, x), "value": _try(S.evaluate, x, figs)} for x in exprs], "figures": figs,
            "scope": [{"viewer": v, "rules": {"branch_manager": "branch"}, "expect": S.scope(rows, v, {"branch_manager": "branch"})}
                      for v in ({"role": "owner"}, {"role": "branch_manager", "branch": "huye"}, {"role": "branch_manager"})], "rows": rows,
            "freshness": [{"u": u, "n": n, "k": k, "expect": S.freshness(u, n, k, ["till-1", "till-2", "web"], ["till-1"])}
                          for u, n in ((0, 5), (0, 6), (100, 1700)) for k in ("live", "daily", "monthly")],
            "exports": [{"start": s, "every": e, "count": 4, "expect": S.export_dates(s, e, 4)} for s in ("2026-01-31", "2024-02-28") for e in ("day", "week", "month")],
            "goals": [{"a": a, "t": t, "e": e, "expect": S.goal(a, t, e)} for a, t in ((500, 1000), (333, 1000), (0, 0), (1, 3), (1500, 1000)) for e in (5000, 3333)],
            "public": S.public_table([{"group": "north", "n": 12, "value": 400}, {"group": "south", "n": 4, "value": 90}, {"group": "east", "n": 5, "value": 0}])}


def ts_source():
    return ("// GENERATED by tools/stats_vectors.py from catalog/stats.v1.json. Do not edit by hand.\n"
            "import type { StatsRegister } from \"./stats.js\";\n"
            f"export const STATS = {json.dumps(S.STAT, ensure_ascii=False, separators=(',', ':'))} as unknown as StatsRegister;\n")


def main():
    vec = json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"
    ts = ts_source()
    if "--check" in sys.argv:
        stale = [p for p, want in ((OUT, vec), (TS, ts)) if not os.path.exists(p) or open(p, encoding="utf-8").read() != want]
        if stale:
            print("out of date:", ", ".join(os.path.relpath(p, ROOT) for p in stale), "- run python3 tools/stats_vectors.py")
            sys.exit(1)
        return
    for p, text in ((OUT, vec), (TS, ts)):
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT), "and", os.path.relpath(TS, ROOT))


if __name__ == "__main__":
    main()
