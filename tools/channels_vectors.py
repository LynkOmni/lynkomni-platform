#!/usr/bin/env python3
"""Shared vectors for the text, USSD and voice channels (BIZZ & DEVICE 48.17): scripted sessions and text messages run through
the Python reference (core/channels.py); the TypeScript port (ts/src/channels.ts) must give the same pages, ends and actions.
  python3 tools/channels_vectors.py          writes contract/vectors/channels.v1.json
  python3 tools/channels_vectors.py --check  fails when the file is out of date (tests/test_channels.py)"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import channels as C  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "channels.v1.json")
CTX = {"products": [["Rice 1 kg", "1,500", "24"], ["Sugar 1 kg", "1,400", "6"], ["Bread", "1,000", "12"]], "today": [3, "4,200"], "receipt": "R-7"}
PIN = "1234"
SESSIONS = [["1", "2", "3", "1234"], ["1", "2", "3", "9999"], ["1", "9", "0"], ["2", "0", "3", "0", "4", "0", "0"], ["1", "1", "0", "abc", "12", "1234"], ["7", "x", "0"]]
SMS = ["1 2 3 1234", "1 2 3", "1 0 3 1234", "2", "3", "4", "5", "", "hello", "1 2 1000 1234", " 3 "]


def build():
    ctx = dict(CTX, pin_ok=lambda t: t == PIN)
    sessions = []
    for inputs in SESSIONS:
        st, steps = C.start(), []
        steps.append({"input": None, "page": C.page(st, CTX), "ends": False, "action": None})
        for x in inputs:
            st, ends, action = C.step(st, x, ctx)
            steps.append({"input": x, "page": C.page(st, CTX), "ends": ends, "action": action})
            if ends: break
        sessions.append(steps)
    return {"description": "Text, USSD and voice channel vectors (core/channels.py is the reference; ts/src/channels.ts must agree). Generated by tools/channels_vectors.py.",
            "ussd_max": C.USSD_MAX, "menu": list(C.MENU), "ctx": CTX, "pin": PIN, "sessions": sessions,
            "sms": [{"text": t, "parsed": C.parse_sms(t)} for t in SMS]}


def main(check=False):
    text = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    if check:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text: print(f"out of date: {OUT} (run python3 tools/channels_vectors.py)"); return 1
        return 0
    open(OUT, "w", encoding="utf-8").write(text); print("wrote", OUT); return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
