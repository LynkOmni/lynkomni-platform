#!/usr/bin/env python3
"""python3 tools/keyboards_vectors.py           writes contract/vectors/keyboards.v1.json and ts/src/keyboards.generated.ts
   python3 tools/keyboards_vectors.py --check   fails when either is out of date (tests/test_keyboard.py)"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import keyboards as K  # noqa: E402

VEC = os.path.join(ROOT, "contract", "vectors", "keyboards.v1.json")
TS = os.path.join(ROOT, "ts", "src", "keyboards.generated.ts")


def build():
    words = {"ko": ["ㅎㅏㄴㄱㅡㄹ", "ㄷㅏㄹㄱㅇㅣ", "ㄱㅗㅏㅇ", "ㅇㅏㄴㄴㅕㅇ"], "ja": ["konnichiha", "sakura", "shinbun", "tsuki"]}
    cases = {"hangul": [], "romaji": [], "ethiopic": [], "kind": []}
    for w in words["ko"]:
        out = ""
        for j in w: out = K.hangul(out, j)
        cases["hangul"].append({"keys": w, "text": out})
    for w in words["ja"]:
        out = ""
        for ch in w: out = K.romaji(out + ch)
        cases["romaji"].append({"keys": w, "text": K.romaji_done(out)})
    for base in "ለመሰበ":
        for o in range(1, 7): cases["ethiopic"].append({"text": "ሰላ" + base, "order": o, "out": K.ethiopic("ሰላ" + base, o)})
    for t, m in (("text", ""), ("email", ""), ("tel", ""), ("number", ""), ("text", "numeric"), ("text", "decimal"), ("search", ""), ("text", "tel")):
        cases["kind"].append({"type": t, "mode": m, "kind": K.kind_of(t, m)})
    return {"description": "Keyboard rules (core/keyboards.py is the reference; ts/src/keyboard.ts must agree). Generated by tools/keyboards_vectors.py.", **cases}


def ts():
    return ("// Generated by tools/keyboards_vectors.py from catalog/keyboards.v1.json. Do not edit.\n"
            f"export const KEYBOARDS = {json.dumps(K.REGISTER, ensure_ascii=False, separators=(',', ':'))} as const;\n")


def main(check=False):
    vec = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    bad = []
    for path, text in ((VEC, vec), (TS, ts())):
        if check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text: bad.append(path)
        else:
            open(path, "w", encoding="utf-8").write(text)
    if bad:
        print("out of date: " + ", ".join(bad)); sys.exit(1)
    if not check: print(f"wrote {VEC} and {TS}")


if __name__ == "__main__":
    main("--check" in sys.argv)
