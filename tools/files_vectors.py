#!/usr/bin/env python3
"""Shared vectors for LynkFiles' rules (SIX SERVICES UPDATE, master blueprint 69.7): core/files.py is the reference and
ts/src/files.ts must agree. Also writes ts/src/files.generated.ts.
  python3 tools/files_vectors.py          writes contract/vectors/files.v1.json and ts/src/files.generated.ts
  python3 tools/files_vectors.py --check  fails when either file is out of date (tests/test_files.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import files as F  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "files.v1.json")
TS = os.path.join(ROOT, "ts", "src", "files.generated.ts")


def _try(f, *a):
    try:
        return {"value": f(*a)}
    except ValueError:
        return {"error": True}


def build():
    samples = ["255044462d312e370a", "89504e470d0a1a0a0000", "ffd8ffe000104a46", "524946460000000057454250", "504b030414000600",
               "4d5a90000300", "7f454c460201", "23212f62696e2f7368", "cafebabe0000", "48656c6c6f2c20776f726c640a", "4361666520c3a92074",
               "48690007", "c328", "", "e4bda0e5a5bd09e4b896e7958c"]
    signers = ["a", "b", "c"]
    sign = [{"o": o, "signed": s, "declined": d} for o in ("in_order", "together", "sideways")
            for s, d in (([], []), (["a"], []), (["b"], []), (["a", "b", "c"], []), (["a"], ["b"]), (["x"], ["y"]))]
    states = [{"signed": s, "declined": d, "exp": e, "can": c} for s, d in (([], []), (["a"], []), (["a", "b", "c"], []), (["a"], ["c"]))
              for e in (False, True) for c in (False, True)]
    links = [{"link": l, "now": n, "pw": p} for l in ({"until": 100}, {"until": 100, "password_set": True}, {"until": 100, "stopped": True})
             for n in (99, 100) for p in (None, True, False)]
    nums = [0, 1, 31, 32, 1234567890123, 2 ** 60 - 1, 2 ** 60, 987654321987654321]
    codes = ["2222-2222-2222", "ABCD-EFGH-JKLM", "abcd-efgh-jkmn", "ABCD-EFGH-JKL", "ABCD-EFGH-JKLI", "ABCD-EFGH-JKLM-NPQR", "ABCDEFGHJKLM", 12, None]
    return {
        "version": 1, "description": "LynkFiles' rules (SIX SERVICES UPDATE 69.7). core/files.py is the reference.",
        "sniff": [{"hex": h, "expect": F.sniff(bytes.fromhex(h))} for h in samples],
        "next": [dict(c, expect=_try(F.next_signers, c["o"], signers, c["signed"], c["declined"])) for c in sign],
        "states": [dict(c, expect=F.request_state(signers, c["signed"], c["declined"], c["exp"], c["can"])) for c in states],
        "share": [dict(c, expect=list(F.share_open(c["link"], c["now"], c["pw"]))) for c in links],
        "days": [{"d": d, "expect": F.share_days_ok(d)} for d in (0, 1, 7, 365, 366, 1.5, True, "7")],
        "format": [{"n": str(n), "expect": F.format_code(n)} for n in nums],
        "codes": [{"c": c, "expect": F.code_ok(c)} for c in codes],
        "fits": [{"u": u, "a": a, "g": g, "x": x, "expect": F.fits(u, a, g, x)} for u, a, g, x in
                 ((0, 1, 5, 0), (5 * F.GB - 1, 1, 5, 0), (5 * F.GB, 1, 5, 0), (5 * F.GB, 1, 5, 1), (10 ** 15, 10 ** 15, None, 0))],
        "levels": [{"l": l, "expect": _try(F.level_partner, l)} for l in ("simple", "identity_checked", "qualified", "notarised")],
    }


def ts_source():
    return ("// GENERATED by tools/files_vectors.py from catalog/files.v1.json. Do not edit by hand.\n"
            "import type { FilesRegister } from \"./files.js\";\n"
            f"export const FILES = {json.dumps(F.FILES, ensure_ascii=False, separators=(',', ':'))} as unknown as FilesRegister;\n")


def main():
    vec = json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"
    ts = ts_source()
    if "--check" in sys.argv:
        stale = [p for p, want in ((OUT, vec), (TS, ts)) if not os.path.exists(p) or open(p, encoding="utf-8").read() != want]
        if stale:
            print("out of date:", ", ".join(os.path.relpath(p, ROOT) for p in stale), "- run python3 tools/files_vectors.py")
            sys.exit(1)
        return
    for p, text in ((OUT, vec), (TS, ts)):
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT), "and", os.path.relpath(TS, ROOT))


if __name__ == "__main__":
    main()
