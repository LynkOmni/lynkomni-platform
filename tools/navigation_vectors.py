#!/usr/bin/env python3
"""Shared vectors for every menu (INTERFACE UPDATE, master blueprint 73): core/navigation.py is the reference and
ts/src/navigation.ts must agree on every case. Also writes the register (with the Business app tabs and the screen templates)
into ts/src/navigation.generated.ts so every app carries it offline.
  python3 tools/navigation_vectors.py          writes contract/vectors/navigation.v1.json and ts/src/navigation.generated.ts
  python3 tools/navigation_vectors.py --check  fails when either file is out of date (tests/test_navigation.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import navigation as N  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "navigation.v1.json")
TS = os.path.join(ROOT, "ts", "src", "navigation.generated.ts")
ROLES = ("owner", "manager", "cashier", "stock_staff", "nobody")
KINDS = ["person"] + list(N.APP["tabs"])


def build():
    families = [p["family"] for p in N._load("products.v1.json")["products"]] + ["lynknothing"]
    bars = []
    for kind in KINDS:
        for tabs in (5, 4):
            for screen in (None, "home", "pay", "shift", "queue_kiosk"):
                for chosen in ({}, {1: "jobs"}, {3: "inbox"}, {2: "jobs"}, {1: "home"}):
                    bars.append({"kind": kind, "tabs": tabs, "screen": screen, "chosen": chosen,
                                 "expect": N.bottom_bar(kind, tabs, screen, chosen)})
    return {"version": 1, "description": "Every menu: groups, headers, bottom bars, quick create, service menus, page tabs and taps from Home. core/navigation.py is the reference; ts/src/navigation.ts must agree.",
            "groups": [{"family": f, "group": N.group_of(f)} for f in families],
            "headers": [{"screen": s, "expect": N.header(s)} for s in N.SCREENS],
            "bars": bars,
            "centres": [{"kind": k, "expect": N.centre(k)} for k in KINDS],
            "quick": [{"role": r, "built": b, "expect": N.quick_create(r, b)} for r in ROLES for b in (None, ["4"], ["4", "4B"])],
            "menus": [{"service": m, "side": side, "expect": [list(x) for x in N.service_menu(m, side)]} for m in N.MENUS for side in ("internal", "external")],
            "page_tabs": [{"tabs": t, "expect": N.page_tabs(t)} for t in (["a"], list("abcdefg"), list("abcdefgh"), list("abcdefghijk"))],
            "taps": {k: N.taps_from_home(k) for k in N.APP["tabs"]}}


def ts_text():
    keep = {k: N.NAV[k] for k in ("groups", "header", "rail", "bottom_bar", "quick_create", "service_menus", "header_ways_in", "children", "three_taps", "often")}
    keep["app_tabs"] = N.APP["tabs"]
    keep["screens"] = N.TEMPLATES["screens"]
    return ("// GENERATED by tools/navigation_vectors.py from catalog/navigation.v1.json, catalog/templates.v1.json and catalog/business-app.v1.json. Do not edit by hand.\n"
            "import type { NavRegister } from \"./navigation.js\";\n"
            f"export const NAV: NavRegister = {json.dumps(keep, ensure_ascii=False, separators=(',', ':'))};\n")


def main(check=False):
    vec = json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"
    ts = ts_text()
    if check:
        bad = [p for p, want in ((OUT, vec), (TS, ts)) if not os.path.isfile(p) or open(p, encoding="utf-8").read() != want]
        if bad:
            print("out of date: " + ", ".join(bad) + " (run python3 tools/navigation_vectors.py)"); return 1
        print("navigation vectors are current"); return 0
    for p, txt in ((OUT, vec), (TS, ts)):
        with open(p, "w", encoding="utf-8") as f: f.write(txt)
    print(f"wrote {OUT} ({len(vec) // 1024} KB) and {TS}"); return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
