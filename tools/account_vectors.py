#!/usr/bin/env python3
"""Shared vectors for the account rules (build section 2): the Python reference (identity/auth.py, identity/account.py) computes
the constants and the verdicts, and the TypeScript port (ts/src/account.ts) must agree. Run after changing either:
  python3 tools/account_vectors.py          writes contract/vectors/account.v1.json
  python3 tools/account_vectors.py --check  fails when the file is out of date (tests/test_account.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from identity import account as A  # noqa: E402
from identity.auth import Identity, RESTRICTED, SITES  # noqa: E402

T0 = 1_800_000_000


def build():
    waits = {"device": 0, "code": Identity.WAIT_S, "assisted": Identity.ASSISTED_S}
    approvals = {"device": 0, "code": 0, "assisted": 2}
    recovery_cases = []
    for path in ("device", "code", "assisted"):
        for dt in (0, 3600, Identity.WAIT_S, Identity.WAIT_S + 1, Identity.ASSISTED_S, Identity.ASSISTED_S + 1):
            for appr in (0, 1, 2):
                ready = dt >= waits[path] and appr >= approvals[path]
                recovery_cases.append({"path": path, "started_at": T0, "approvals": appr, "now": T0 + dt, "ready": ready, "ready_at": T0 + waits[path]})
    restriction_cases = [{"action": a, "restricted_until": T0 + A.DAY, "now": n, "allowed": not (a in RESTRICTED and n < T0 + A.DAY)}
                         for a in ("change_role", "change_payout", "revoke_device", "export_data", "record_sale", "view_reports") for n in (T0, T0 + A.DAY - 1, T0 + A.DAY)]
    consent_cases = [{"scope": sc, "days": d, "now": T0, "expires": T0 + min(max(1, d), A.MAX_CONSENT_DAYS[sc]) * A.DAY} for sc in sorted(A.CONSENT_SCOPES) for d in (1, 7, 30, 90, 365, 400)]
    standing_cases = [{"cap_minor": 5000, "amount_minor": a, "revoked": r, "provider_ready": p, "allowed": p and not r and 0 < a <= 5000}
                      for a in (0, 1, 4999, 5000, 5001) for r in (False, True) for p in (True, False)]
    payout_cases = [{"second_device_ok": ok, "now": T0, "status": "applied" if ok else "waiting", "ready_at": T0 if ok else T0 + A.PAYOUT_WAIT_S} for ok in (True, False)]
    return {
        "description": "Shared vectors for the LynkOmni Account rules (build section 2). Python is the reference; ts/src/account.ts must agree. Generated by tools/account_vectors.py.",
        "constants": {"session_s": Identity.SESSION_S, "stepup_s": Identity.STEPUP_S, "sites": sorted(SITES), "restricted_after_recovery": sorted(RESTRICTED), "restriction_s": A.DAY,
                      "recovery_wait_s": waits, "recovery_approvals": approvals, "payout_wait_s": A.PAYOUT_WAIT_S, "data_request_days": A.DATA_REQUEST_DAYS,
                      "close_grace_days": A.CLOSE_GRACE_DAYS, "max_consent_days": A.MAX_CONSENT_DAYS, "registration_steps": list(A.REGISTRATION_STEPS), "pages": list(A.PAGES)},
        "recovery": recovery_cases, "restriction": restriction_cases, "consent": consent_cases, "standing": standing_cases, "payout": payout_cases,
    }


def main(check=False):
    path = os.path.join(ROOT, "contract", "vectors", "account.v1.json")
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if check:
        if not os.path.isfile(path) or open(path, encoding="utf-8").read() != text:
            print("contract/vectors/account.v1.json is out of date: run python3 tools/account_vectors.py"); return 1
        print("account vectors are current"); return 0
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(path, ROOT)}"); return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
