#!/usr/bin/env python3
"""LynkDriver vectors and the TypeScript register (BIZZ & DEVICE): the Python reference (core/drivers.py) decides the update state
for installed versions at many moments; ts/src/drivers.ts must agree.
  python3 tools/drivers_vectors.py          writes contract/vectors/drivers.v1.json and ts/src/drivers.generated.ts
  python3 tools/drivers_vectors.py --check  fails when either is out of date (tests/test_drivers.py)"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import drivers as D  # noqa: E402

VEC = os.path.join(ROOT, "contract", "vectors", "drivers.v1.json")
TS = os.path.join(ROOT, "ts", "src", "drivers.generated.ts")


def build():
    t0 = D.PACK["released_at"]
    moments = [t0 - D.DAY, t0, t0 + D.DAY, t0 + 3 * D.DAY, t0 + 7 * D.DAY - 1, t0 + 7 * D.DAY, t0 + 30 * D.DAY]
    installed = [None, "1.0.0", "1.2.0", "1.3.0", "1.3.1", "1.3.2", "1.4.0", "1.10.0"]
    cases = [{"installed": i, "now": n, "state": D.update_state(i, n)} for i in installed for n in moments]
    kinds = [k["id"] for k in D.REGISTER["kinds"]]
    return {"description": "LynkDriver update states (core/drivers.py is the reference; ts/src/drivers.ts must agree). Generated by tools/drivers_vectors.py.",
            "cases": cases, "install": [{"kinds": kinds[:3], "installed": None, "needs": D.needs_install(kinds[:3], None)}, {"kinds": kinds[:3], "installed": "1.4.0", "needs": []}],
            "fallback": {k: D.fallback(k) for k in kinds}}


def ts():
    r = {k: D.REGISTER[k] for k in ("pack", "previous", "update_days", "where", "kinds")}
    return ("// Generated by tools/drivers_vectors.py from catalog/drivers.v1.json. Do not edit.\n"
            'import type { DriverRegister } from "./drivers.js";\n'
            f"export const DRIVERS: DriverRegister = {json.dumps(r, ensure_ascii=False, separators=(',', ':'))} as DriverRegister;\n")


def main(check=False):
    vec = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    bad = []
    for path, text in ((VEC, vec), (TS, ts())):
        if check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text: bad.append(path)
        else:
            open(path, "w", encoding="utf-8").write(text)
    if check and bad:
        print("out of date: " + ", ".join(bad) + " (run python3 tools/drivers_vectors.py)"); return 1
    if not check: print("wrote", VEC, "and", TS)
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
