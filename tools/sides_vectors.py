#!/usr/bin/env python3
"""Shared vectors for the two sides (BIZZ & DEVICE, 2026-11-09): core/sides.py is the reference and ts/src/sides.ts must
agree on every case. Also writes the Storefront address rule into ts/src/sides.generated.ts so the apps carry it offline.
  python3 tools/sides_vectors.py          writes contract/vectors/sides.v1.json and ts/src/sides.generated.ts
  python3 tools/sides_vectors.py --check  fails when either file is out of date (tests/test_sides.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import sides as S  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "sides.v1.json")
TS = os.path.join(ROOT, "ts", "src", "sides.generated.ts")
ADDR = json.load(open(os.path.join(ROOT, "catalog", "addresses.v1.json"), encoding="utf-8"))
EXTRA = ["/", "/external", "/externality", "/external/sell?view=all", "/sell#top",
         "shop.lynkomni.com/grace", "shop.lynkomni.com/grace/courses/LOLST-6837-8950-1932", "shop.lynkomni.com/grace/products/LOLST-6837-8950-1932?view=wholesale",
         "shop.lynkomni.com/grace/tables/4", "shop.lynkomni.com/grace/reviews", "shop.lynkomni.com/explore/courses", "shop.lynkomni.com/explore/anything",
         "shop.lynkomni.com/track/LOORD-5499-1341-4781", "shop.lynkomni.com/", "pay.lynkomni.com/listings/LOLST-6837-8950-1932",
         "pay.lynkomni.com/r/LORCP-2176-0474-0548", "account.lynkomni.com/orders/LOORD-5499-1341-4781", "lynkomni.com/download/driver",
         "app.lynkomni.com/external/business", "app.lynkomni.com/business"]


def build():
    cases = [{"address": a, "side": S.side_of(a)} for a in ADDR["app_paths"] + EXTRA]
    kinds = [{"path": p, "kind": S.kind(p)} for p in ADDR["app_paths"]]
    twins = [{"workspace": m, "storefront": S.storefront_path(m)} for m in S.RULE["mirrors"]]
    return {"version": 1, "description": "The two sides: which side an address is on, what kind each app path is, and each mirrored path's Storefront twin. core/sides.py is the reference; ts/src/sides.ts must agree.",
            "sides": cases, "kinds": kinds, "twins": twins}


def ts_text():
    r = S.RULE
    keep = {k: r[k] for k in ("prefix", "mirrors", "storefront_only", "shared", "workspace_only")}
    keep["lists"] = r["public"]["lists"]
    return ("// GENERATED by tools/sides_vectors.py from catalog/addresses.v1.json (storefront). Do not edit by hand.\n"
            "import type { SideRule } from \"./sides.js\";\n"
            f"export const SIDE_RULE: SideRule = {json.dumps(keep, ensure_ascii=False)};\n")


def main(check=False):
    vec = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    ts = ts_text()
    if check:
        bad = [p for p, want in ((OUT, vec), (TS, ts)) if not os.path.isfile(p) or open(p, encoding="utf-8").read() != want]
        if bad:
            print("out of date: " + ", ".join(bad) + " (run python3 tools/sides_vectors.py)"); return 1
        print("sides vectors are current"); return 0
    for p, txt in ((OUT, vec), (TS, ts)):
        with open(p, "w", encoding="utf-8") as f: f.write(txt)
    print(f"wrote {OUT} and {TS}"); return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
