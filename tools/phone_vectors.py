#!/usr/bin/env python3
"""Shared vectors for the phone and email checks (section 4C point 1): core/phone.py is the reference and ts/src/phone.ts must
agree. Also writes ts/src/phone.generated.ts with the email domains of catalog/email-domains.v1.json.
  python3 tools/phone_vectors.py          writes contract/vectors/phone.v1.json and ts/src/phone.generated.ts
  python3 tools/phone_vectors.py --check  fails when either file is out of date (tests/test_phone.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import phone as P  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "phone.v1.json")
TS = os.path.join(ROOT, "ts", "src", "phone.generated.ts")
COUNTRIES = ["HU", "XX", "CM", "GB", "US", "CA", "AG", "DE", "IN", "RU", "FR", "NG", "BR", "JP", "AQ"]
TYPED = ["88123456789", "8123456789", "18005550100", "06201234567", "\u0666\u0667\u0661\u0662\u0663\u0664\u0665\u0666\u0667", "\u096c\u096d\u0967", "\uff16\uff17\uff11", "", "0", "1", "2", "5", "6", "61", "67", "671", "6712345", "671234567", "6712345678", "071234567", "07400123456", "7400123456",
         "74001234567", "2125550100", "212555", "4165550100", "9123456789", "15123456789", "1512345678", "8012345678", "612345678", "11987654321", "9012345678"]
PASTED = ["+237 6 71 23 45 67", "+44 7400 123456", "0044 7400 123456", "+1 212 555 0100", "+1 416 555 0100", "+1 268 464 1234", "+7 912 345 67 89",
          "07400 123456", "6 71 23 45 67", "+999 612 345 678", "+49 151 23456789", "+33 6 12 34 56 78", "abc", ""]
EMAILS = ["", "a@b", "name@example.com", "x@gmial.com", "y@hotmial.com", "z@yaho.com", "q@mailinator.com", "w@qq.co", "e@company.cm", "bad..dots@ex.com",
          "spaces in@ex.com", "a@sub.domain.org", "info@lynkomni.co"]


def _pack(c):
    r = P.rules(c)
    if r is P.GENERIC: return None
    k = lambda x: {"lengths": x["lengths"], "groups": x["groups"], "sample": x["sample"]}
    return {"code": r["code"], "prefix": r["prefix"], "main": r["main"], "mobile": k(r["mobile"]), "any": k(r["any"])}


def build():
    codes = P.all_codes()
    used = {"237", "44", "1", "7", "49", "33", "999"}
    packs = {c: _pack(c) for c in sorted({c for cc in used for c in codes.get(cc, [])} | set(COUNTRIES))}
    cases = []
    for c in COUNTRIES:
        r = P.rules(c)
        for t in TYPED:
            d = P.clean(r, t)
            for mobile in (True, False):
                cases.append({"country": c, "typed": t, "mobile": mobile, "clean": d, "state": P.check(r, d, mobile)["state"],
                              "submit": P.check(r, d, mobile, submit=True)["state"], "accept": P.accept(r, d, mobile), "groups": P.groups(r, P.accept(r, d, mobile), mobile)})
        cases.append({"country": c, "sample": {"mobile": P.sample(r, True), "any": P.sample(r, False)},
                      "lengths": P.lengths_text(r["mobile"]["lengths"]), "international": P.international(r, r["mobile"]["sample"] or "123456")})
    pasted = [{"current": cur, "text": t, "result": list(P.read_pasted(t, cur, codes))} for cur in ("XX", "CM", "GB") for t in PASTED]
    waits = [{"sent": sent, "now": now, "wait": P.resend_wait(sent, now)} for sent, now in (([], 0), ([0], 10), ([0], 30), ([0, 30], 40), ([0, 30], 100), ([0, 30, 90], 120), ([0, 30, 90, 210, 510], 600), ([0, 30, 90, 210, 510], 3700))]
    emails = [{"text": e, "deep": deep, "result": P.check_email(e, deep)} for e in EMAILS for deep in (False, True)]
    return {"version": 1, "description": "Phone and email check cases shared by core/phone.py and ts/src/phone.ts (section 4C point 1). The packs are the countries the cases need, as pages carry them.",
            "codes": codes, "packs": packs, "cases": cases, "pasted": pasted, "emails": emails, "waits": waits}


def zeros():
    """The zero of every decimal digit block, so ts/src/phone.ts reads any script's digits the same as unicodedata."""
    import unicodedata
    return [c for c in range(0x80, 0x1FBF0) if unicodedata.decimal(chr(c), None) == 0]


def ts_text():
    d = {"common": P.COMMON, "throwaway": sorted(P.THROWAWAY)}
    return ("// Generated by tools/phone_vectors.py from catalog/email-domains.v1.json. Do not edit by hand.\n"
            "import type { EmailDomains } from \"./emailfield.js\";\n"
            f"export const EMAIL_DOMAINS: EmailDomains = {json.dumps(d, ensure_ascii=False)};\n"
            f"/** Codes sent to a phone or an email (core/phone.py CODES): length, lifetime, the growing wait before another, and the hour's limit. */\n"
            f"export const CODES = {json.dumps(P.CODES)};\n"
            f"/** The zero of every decimal digit block after ASCII (Unicode Nd), for reading digits typed in any script. */\n"
            f"export const DIGIT_ZEROS: number[] = {json.dumps(zeros())};\n")


def main(argv):
    v = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    t = ts_text()
    if "--check" in argv:
        old_v = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        old_t = open(TS, encoding="utf-8").read() if os.path.exists(TS) else ""
        if old_v != v or old_t != t:
            print("phone vectors are out of date (run python3 tools/phone_vectors.py)"); return 1
        print("phone vectors are up to date"); return 0
    open(OUT, "w", encoding="utf-8").write(v); open(TS, "w", encoding="utf-8").write(t)
    print(f"wrote {OUT} and {TS}"); return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
