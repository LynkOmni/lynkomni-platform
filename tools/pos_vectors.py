#!/usr/bin/env python3
"""Shared vectors for the Business app and LynkPOS rules (build section 3): the Python reference (merchant/) computes the
constants and verdicts, and the TypeScript port (ts/src/business.ts, agent.ts, restaurant.ts) must agree. Run after changing either:
  python3 tools/pos_vectors.py          writes contract/vectors/pos.v1.json
  python3 tools/pos_vectors.py --check  fails when the file is out of date (tests/test_merchant.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from merchant import agent as AG, automations as AU, business as B, devices as D, restaurant as R  # noqa: E402
from core import workspaces as WS  # noqa: E402
from services import billing  # noqa: E402

TIERS = ("free", "plus", "pro", "max")


def entitlement(family, tier):
    out = {}
    for d in billing.FEATURES[family][: billing.FAMILIES[family][2].index(tier) + 1]: out.update(d)
    return out


def build():
    web = [{"action": a, "registered": r, "rule": D.web_rule(a, r)} for a in D.TILL_ACTIONS + D.STEP_UP_IN_BROWSER + ("accounting", "chats", "reports") for r in (True, False)]
    limits = [{"amount": a, "used_today": u, "partner": {"per_transaction": 200_000, "per_day": 2_000_000}, "pack": p,
               "result": "limit_exceeded" if a > min(200_000, (p or {}).get("per_transaction", 10**12)) or u + a > min(2_000_000, (p or {}).get("per_day", 10**12)) else "ok"}
              for a in (1, 100_000, 200_000, 200_001) for u in (0, 1_900_000) for p in (None, {"per_transaction": 150_000}, {"per_day": 1_950_000})]
    low = [{"balance": b, "usual": u, "low": bool(u > 0 and b < u * AG.LOW_FLOAT_RATIO)} for b in (0, 1_000, 19_999, 20_000, 50_000) for u in (0, 100_000)]
    cash = [{"state": s, "may_hand_over_cash": s == "confirmed"} for s in ("queued", "sent", "accepted", "confirmed", "failed")]
    statement = {"ours": {"r1": 50, "r2": 70, "r3": 10}, "rows": [{"request_id": "r1", "commission": 50}, {"request_id": "r2", "commission": 77}, {"request_id": "r9", "commission": 5}]}
    s_m, s_t, s_mm = 1, 50, ["r2", "r9", "r3"]
    tiers = {}
    for t in TIERS:
        e = entitlement("lynkpos", t); co = entitlement("lynkcheckout", t)
        hi = lambda k: None if e.get(k) is None or co.get(k) is None else max(e[k], co[k])
        tiers[t] = {"receipts": e.get("receipts"), "tables": e.get("tables"), "kitchen_output": R.KITCHEN_WITHOUT_SCREEN if e.get("kitchen_screens", 0) == 0 else "screen",
                    "tips": bool(e.get("tips")), "table_qr_ordering": bool(e.get("table_qr_ordering")), "agent_partners": e.get("agent_partners"), "outlets": e.get("outlets"), "devices": e.get("devices"),
                    "delivery": {"partner_deliveries_per_month": hi("partner_deliveries_per_month"), "own_riders": hi("own_riders"), "routing": bool(e.get("delivery_routing") or co.get("delivery_routing"))},
                    "may_open_group": t in ("pro", "max"), "entitlement": e, "checkout_entitlement": co}
    voice = [{"text": "two bags of rice, one soap", "products": [{"id": "p1", "name": "Rice"}, {"id": "p2", "name": "Soap"}], "lines": [["p1", 2000], ["p2", 1000]]},
             {"text": "3 soap and rice", "products": [{"id": "p1", "name": "Rice"}, {"id": "p2", "name": "Soap"}], "lines": [["p2", 3000], ["p1", 1000]]},
             {"text": "bread", "products": [{"id": "p1", "name": "Rice"}], "lines": []}]
    for v in voice: assert [list(x) for x in B.Business.parse_voice(v["text"], v["products"])] == v["lines"]
    home = [{"role": r, "staff_see_profit": sp, "pending": pe, "low": lo, "negative": 0, "unread": un, "cards": B.Business.home_cards(r, sp, pe, lo, 0, un)}
            for r in ("owner", "cashier") for sp in (False, True) for pe in (0, 3) for lo in (0, 2) for un in (0, 1)]
    sync = [{"pending": p, "order": [k for k in AU.SYNC_ORDER if p.get(k)]} for p in ({"media": 2, "sales": 3}, {"chats": 1}, {}, {"payments": 1, "stock": 1, "media": 1, "sales": 1, "chats": 1})]
    return {
        "description": "Shared vectors for the Business app and LynkPOS rules (build section 3). Python is the reference; ts/src/business.ts, agent.ts and restaurant.ts must agree. Generated by tools/pos_vectors.py.",
        "constants": {"business_types": list(B.TYPES), "tabs": {k: list(v) for k, v in B.TABS.items()}, "setup_steps": list(B.SETUP_STEPS), "handheld_tiles": list(B.HANDHELD_TILES),
                      "fast_checkout": list(B.FAST_CHECKOUT), "receipt_channels": list(B.RECEIPT_CHANNELS), "business_sections": list(B.BUSINESS_SECTIONS), "till_actions": list(D.TILL_ACTIONS),
                      "agent_services": list(AG.SERVICES), "collection_kinds": list(AG.COLLECTION_KINDS), "finance_products": list(AG.FINANCE_PRODUCTS), "agent_states": list(AG.STATES),
                      "low_float_ratio": AG.LOW_FLOAT_RATIO, "idle_lock_s": AU.IDLE_LOCK_S, "sync_order": list(AU.SYNC_ORDER), "device_kinds": list(D.KINDS), "kitchen_without_screen": R.KITCHEN_WITHOUT_SCREEN,
                      "tip_share": R.Restaurant.tip_share_for_lynkomni(1000), "delivery_share_cents": billing.SERVICE_FEES["delivery_share_cents"], "proof_warning_key": B.PROOF_WARNING_KEY},
        "web_rule": web, "limit_check": limits, "low_float": low, "cash": cash, "statement": {**statement, "matched": s_m, "total": s_t, "mismatches": s_mm},
        "tiers": tiers, "voice": voice, "home_cards": home, "sync": sync,
        "workspaces": [{"entity": e, "type": t, "tabs": list(WS.tabs(e, t, B.TABS[t])), "words": {k: WS.word(e, k) for k in ("tab_customers", "tab_business", "it_customers", "tab_home")},
                        "accounts": {c["id"]: WS.account_for(e, c["id"]) for side in ("income", "expense") for c in WS.categories(e)[side]}, "office": [f for f in billing.FAMILIES if WS.office_ok(f)]}
                       for e in WS.ENTITIES for t in B.TYPES],
    }


def main(check=False):
    path = os.path.join(ROOT, "contract", "vectors", "pos.v1.json")
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if check:
        if not os.path.isfile(path) or open(path, encoding="utf-8").read() != text:
            print("contract/vectors/pos.v1.json is out of date: run python3 tools/pos_vectors.py"); return 1
        print("pos vectors are current"); return 0
    with open(path, "w", encoding="utf-8") as f: f.write(text)
    print(f"wrote {os.path.relpath(path, ROOT)}"); return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
