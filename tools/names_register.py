#!/usr/bin/env python3
"""Every Lynk name and its plain word (owner, 21 November 2026). core/names.py is the reference; ts/src/names.ts must agree.
Writes ts/src/names.generated.ts (the register and the English words, so every page works offline) and the shared vectors.
  python3 tools/names_register.py          writes contract/vectors/names.v1.json and ts/src/names.generated.ts
  python3 tools/names_register.py --check  fails when either file is out of date (tests/test_names.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import names as N  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "names.v1.json")
TS = os.path.join(ROOT, "ts", "src", "names.generated.ts")
TEXTS = ["Ask LynkAssist about LynkStat.", "LynkPOS Pro includes LynkRewards Plus.", "LynkOmni runs LynkBooking Pass.",
         "Open LynkPOSX or MyLynkStat", "LynkTab (counter) and LynkKiosk", "LynkDash is gone; LynkDVBox stays inside.", "No names here."]


def build():
    return {"version": 1, "description": "Every Lynk name and its plain word. core/names.py is the reference; ts/src/names.ts must agree.",
            "find": [{"text": t, "expect": N.find(t)} for t in TEXTS],
            "unknown": [{"text": t, "expect": N.unknown(t)} for t in TEXTS + ["LynkWidget is new", "LynkCCBox"]],
            "labels": [{"name": n["name"], "brand_first": N.label(n["name"]), "plain_first": N.label(n["name"], mode="plain_first"),
                        "part_of": N.part_of(n["name"]), "icon": N.icon_of(n["name"]), "spoken": N.spoken(n["name"]),
                        "similar": N.similar(n["name"])} for n in N.NAMES],
            "speakable": [{"text": t, "expect": N.speakable(t)} for t in TEXTS],
            "explain": [{"text": t, "expect": N.explain_text(t), "plain_first": N.explain_text(t, mode="plain_first")} for t in TEXTS + ["Paid with LynkCheckout. LynkCheckout again."]],
            "paper": [{"lines": l, "width": w, "expect": N.paper_lines(l, width=w)} for l, w in ((["Paid by LynkCheckout", "LynkMPay"], 24), (["Thank you"], 32), (["LynkPOS LynkPOS"], 42))],
            "check_plain": [{"word": w, "expect": N.check_plain(w)} for w in ("Pay links & QR", "Customer CRM", "LynkStat numbers", "Assistant IA", "Webhook tools")],
            "now_called": [{"old": o, "expect": N.now_called(o)} for o in list(N.NOW_CALLED) + ["LynkShield"]]}


def ts():
    with open(os.path.join(ROOT, "web", "names", "strings.en.json"), encoding="utf-8") as f:
        plain = json.load(f)
    with open(os.path.join(ROOT, "web", "nameinfo", "strings.en.json"), encoding="utf-8") as f:
        info = json.load(f)
    reg = {k: N.REGISTER[k] for k in ("max_plain_chars", "company", "internal", "retired", "names", "now_called", "similar", "familiar_after", "plain_word_check", "asks")}
    en = {"plain": {k: v for k, v in plain.items() if k.startswith("nm_") and k[3:] in N.BY_ID},
          "about": {k: v for k, v in info.items() if k.startswith("nma_")}}
    return ("// GENERATED by tools/names_register.py from catalog/names.v1.json, web/names and web/nameinfo. Do not edit by hand.\n"
            "import type { NamesRegister } from \"./names.js\";\n"
            f"export const NAMES_REG: NamesRegister = {json.dumps(reg, ensure_ascii=False, separators=(',', ':'))};\n"
            f"export const NAMES_EN: {{ plain: Record<string, string>; about: Record<string, string> }} = {json.dumps(en, ensure_ascii=False, separators=(',', ':'))};\n")


def main(check=False):
    vec = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    out = {OUT: vec, TS: ts()}
    stale = [p for p, body in out.items() if not os.path.isfile(p) or open(p, encoding="utf-8").read() != body]
    if check:
        if stale:
            print("out of date: " + ", ".join(os.path.relpath(p, ROOT) for p in stale) + " (run python3 tools/names_register.py)")
            return 1
        return 0
    for p, body in out.items():
        with open(p, "w", encoding="utf-8") as f:
            f.write(body)
    print(f"wrote {len(N.NAMES)} names")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
