#!/usr/bin/env python3
"""Shared vectors for the office side of gift cards, store credit, deposits, matching and payment costs (SERVICES UPDATE 67.2 and
67.8): core/office_money.py is the reference and ts/src/officemoney.ts must agree. Also writes ts/src/officemoney.generated.ts with the
register's numbers (catalog/office-money.v1.json).
  python3 tools/office_money_vectors.py          writes contract/vectors/office-money.v1.json and ts/src/officemoney.generated.ts
  python3 tools/office_money_vectors.py --check  fails when either file is out of date (tests/test_office_money.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import office_money as O  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "office-money.v1.json")
TS = os.path.join(ROOT, "ts", "src", "officemoney.generated.ts")


def _try(f, *a):
    try:
        return {"value": f(*a)}
    except ValueError:
        return {"error": True}


def _mv(i, k, a):
    return {"id": i, "kind": k, "amount": a}


def build():
    bal = [
        [_mv("g1", "issue", 5000), _mv("g1", "spend", 2000), _mv("g2", "issue", 1000), _mv("g1", "issue", 500)],
        [_mv("g1", "issue", 1000), _mv("g1", "spend", 1500), _mv("g1", "spend", 100)],
        [_mv("g1", "issue", 1000), _mv("g1", "spend", 1000)],
        [_mv("g1", "issue", 0)], [_mv("g1", "issue", 10.5)], [],
    ]
    dep = [(5000, []), (5000, [2000, 3000]), (5000, [2000]), (5000, [6000]), (5000, [0]), (0, []), (5000, [1.5])]
    T = [{"kind": "sale", "id": "s1", "ref": "R1", "amount": 1500, "currency": "RWF", "on": "2026-11-10"},
         {"kind": "invoice", "id": "i1", "amount": 9000, "currency": "RWF", "on": "2026-11-08"},
         {"kind": "booking", "id": "b1", "amount": 4000, "currency": "RWF", "on": "2026-11-10"},
         {"kind": "booking", "id": "b2", "amount": 4000, "currency": "RWF", "on": "2026-11-11"},
         {"kind": "sale", "id": "s2", "amount": 700, "currency": "USD", "on": "2026-11-01"}]
    P = [{"ref": "R1", "amount": 1500, "currency": "RWF", "on": "2026-11-12"},
         {"ref": "R2", "amount": 9000, "currency": "RWF", "on": "2026-11-10"},
         {"ref": "R3", "amount": 4000, "currency": "RWF", "on": "2026-11-11"},
         {"ref": "R4", "amount": 700, "currency": "USD", "on": "2026-11-09"},
         {"ref": "R5", "amount": 700, "currency": "RWF", "on": "2026-11-01"}]
    matches = [(P, T, None), (P, T, 10), (P[:1], [dict(T[0], amount=1400)], None), ([], T, None), (P, [], None)]
    C = [{"ref": "R1", "on": "2026-11-12", "currency": "RWF", "amount": 1500, "provider_fee": 30, "lynkomni_part": 8},
         {"ref": "R2", "on": "2026-11-30", "currency": "RWF", "amount": 9000, "provider_fee": 180, "lynkomni_part": 45},
         {"ref": "R3", "on": "2026-12-01", "currency": "RWF", "amount": 4000, "provider_fee": 80, "lynkomni_part": 0},
         {"ref": "R4", "on": "2026-11-09", "currency": "USD", "amount": 700, "provider_fee": 21, "lynkomni_part": 4}]
    costs = [C, [], [dict(C[0], provider_fee=-1)], [dict(C[0], provider_fee=1500, lynkomni_part=1)], [dict(C[0], lynkomni_part=0.5)]]
    S = [{"id": "p1", "expected_on": "2026-11-10", "amount": 5000, "currency": "RWF"}, {"id": "p2", "expected_on": "2026-11-18", "amount": 800, "currency": "RWF"},
         {"id": "p3", "expected_on": "2026-11-20", "amount": 300, "currency": "USD"}, {"id": "p0", "expected_on": "2026-11-10", "amount": 10, "currency": "RWF"}]
    pays = [(S, {"p1": "2026-11-11"}, "2026-11-21"), (S, {}, "2026-11-20"), (S, {"p3": "2026-11-20"}, "2026-11-12"), ([], {}, "2026-11-21")]
    return {
        "version": 1, "description": "The office side of gift cards, store credit, deposits, matching and payment costs (67.2, 67.8). core/office_money.py is the reference.",
        "balances": [{"a": b, "expect": _try(O.balances, b)} for b in bal],
        "deposit": [{"a": [t, s], "expect": _try(O.deposit_left, t, s)} for t, s in dep],
        "match": [{"a": [p, t, w], "expect": _try(O.match, p, t, w)} for p, t, w in matches],
        "costs": [{"a": c, "expect": _try(O.costs, c)} for c in costs],
        "payouts": [{"a": [s, a, d], "expect": _try(O.payouts, s, a, d)} for s, a, d in pays],
    }


def ts_source():
    M = O.MONEY
    return ("// GENERATED by tools/office_money_vectors.py from catalog/office-money.v1.json. Do not edit by hand.\n"
            f"export const WINDOW_DAYS = {M['matching']['window_days']};\n"
            f"export const LATE_AFTER_DAYS = {M['payouts']['late_after_days']};\n")


def main():
    vec = json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"
    ts = ts_source()
    if "--check" in sys.argv:
        stale = [p for p, want in ((OUT, vec), (TS, ts)) if not os.path.exists(p) or open(p, encoding="utf-8").read() != want]
        if stale:
            print("out of date:", ", ".join(os.path.relpath(p, ROOT) for p in stale), "- run python3 tools/office_money_vectors.py")
            sys.exit(1)
        return
    for p, text in ((OUT, vec), (TS, ts)):
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT), "and", os.path.relpath(TS, ROOT))


if __name__ == "__main__":
    main()
