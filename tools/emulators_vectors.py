#!/usr/bin/env python3
"""Emulator Panel vectors and the TypeScript register (EMULATOR UPDATE, build section 3A): the Python reference (core/emulators.py)
decides slots, counting, the check before assigning, hardware ways, key tones, the delivery menu, states and screen fit;
ts/src/emulators.ts must agree.
  python3 tools/emulators_vectors.py          writes contract/vectors/emulators.v1.json and ts/src/emulators.generated.ts
  python3 tools/emulators_vectors.py --check  fails when either is out of date (tests/test_emulator_panel.py)"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import emulators as E  # noqa: E402
from services import billing  # noqa: E402

VEC = os.path.join(ROOT, "contract", "vectors", "emulators.v1.json")
with open(os.path.join(ROOT, "design", "tokens.v1.json"), encoding="utf-8") as _f:          # the one shared tone set lives in the design tokens
    SOUNDS = {k: v for k, v in json.load(_f)["sounds"].items() if k != "note"}
TS = os.path.join(ROOT, "ts", "src", "emulators.generated.ts")
TIERS = ("free", "plus", "pro", "max")


def register():
    """Only what the rules read travels to the apps: each emulator's family, counting, touch check and needs, and the slots."""
    ems = [{"id": e["id"], "service": e["service"], "counted": e["counted"], "shared_with": e["shared_with"], "touch": e["checks"]["touch"] is True,
            "user": e["user"], "planned": e["planned"], "customer_facing": e["customer_facing"], "hardware": e["hardware"], "devices": e["devices"], "min_short_side_px": e["needs"]["min_short_side_px"], "outputs": e["needs"]["outputs"]} for e in E.REG["emulators"]]
    fams = sorted({e["shared_with"] or e["service"] for e in E.REG["emulators"] if e["counted"]})
    names = {f: billing.FAMILIES[f][1] for f in sorted({e["service"] for e in E.REG["emulators"]} | set(fams))}     # short product names, never typed in code
    return {"emulators": ems, "names": names, "slots": {f: {t: E.slots(f, t) for t in TIERS} for f in fams}, "extra_slot_cents": E.extra_slot_cents(),
            "code_minutes": E.CODE_MINUTES, "reapprove_days": E.REAPPROVE_DAYS, "downgrade_grace_days": E.DOWNGRADE_GRACE_DAYS,
            "artwork_min_px": E.ARTWORK_MIN_PX, "sounds": SOUNDS, "hardware_ways": {k: list(v) for k, v in E.HARDWARE_WAYS.items()}, "os_ways": {k: list(v) for k, v in E.OS_WAYS.items()}}


def build():
    ids = [e["id"] for e in E.REG["emulators"]]
    phone = {"device": "d1", "emulator": "pos.merchant_phone", "connected": True}
    conns = [phone, {"device": "d1", "emulator": "rewards.till", "connected": True}, {"device": "d2", "emulator": "pos.counter_tablet", "connected": True},
             {"device": "d3", "emulator": "pos.terminal", "connected": True, "practice": True}, {"device": "d4", "emulator": "queue.board", "connected": True},
             {"device": "d5", "emulator": "pos.kitchen_screen", "connected": False}]
    fams = sorted({E.counts_for(i) for i in ids if E.counts_for(i)})
    capses = [{"short_side": 390, "touch": True, "camera": True, "speaker": True, "os": "android"},
              {"short_side": 1080, "touch": False, "keys": True, "speaker": True, "os": "tv"},
              {"short_side": 200, "touch": True, "os": "android"}, {"short_side": 800, "os": "windows"},
              {"short_side": 800, "touch": True, "keys": False, "os": "ios", "hardware": ["scanner"]}]
    managers = [{}, {"tones": False}, {"volume": "high", "user_may_change": False, "pin_same_tone": True}, {"volume": "loud"}]
    users = [None, {"tones": False, "volume": "low"}, {"vibration": False}]
    moments = [(0, 0), (0, 599), (0, 600), (0, 601), (100, 50)]
    return {"description": "Emulator Panel rules (core/emulators.py is the reference; ts/src/emulators.ts must agree). Generated by tools/emulators_vectors.py.",
            "counts_for": {i: E.counts_for(i) for i in ids},
            "in_use": {f: E.in_use(f, conns) for f in fams},
            "may_connect": [{"limit": lim, "family": "lynkpos", "new": new, "extra": ex, "result": list(E.may_connect(lim, "lynkpos", conns, new, ex))}
                            for lim in (1, 2, 5, None, "own_units") for ex in (0, 1)
                            for new in ({"device": "d9", "emulator": "pos.terminal"}, {"device": "d1", "emulator": "pay.till"}, {"device": "d9", "emulator": "pos.customer_display"}, {"device": "d9", "emulator": "pos.terminal", "practice": True})],
            "code_valid": [{"issued": a, "now": b, "used": u, "valid": E.code_valid(a, b, u)} for a, b in moments for u in (False, True)],
            "new_code": [{"n": n, "code": E.new_code(n)} for n in (0, 1, 31, 32, 1_000_000, 1_073_741_823, 1_073_741_824)],
            "can_run": [{"emulator": i, "caps": c, "result": E.can_run(i, c)} for i in ids for c in capses],
            "hardware": [{"kind": k, "os": o, "advice": E.hardware_advice(k, o)} for k in E.HARDWARE_WAYS for o in E.OS_WAYS],
            "tones": [{"manager": m, "user": u, "customer_facing": cf, "silent": si, "quiet_hours": q, "vibrates": v, "result": E.tones(m, u, cf, si, q, v)}
                      for m in managers for u in users for cf in (False, True) for si, q in ((False, False), (True, False), (False, True)) for v in (True, False)],
            "delivery": [{"caps": c, "online": on, "printer_ready": pr, "customer_known": ck, "contact_given": cg, "ways": E.delivery_ways(c, on, pr, ck, cg)}
                         for c in ({}, {"device_print": True}, {"nearby": True}) for on in (True, False) for pr in (True, False) for ck in (True, False) for cg in (True, False)],
            "request_state": {s: E.request_state(s) for s in ("made_offline", "offered", "accepted", "connected", "denied", "expired", "disconnect_sent", "disconnected")},
            "reapproval_due": [{"last": a, "today": b, "due": E.reapproval_due(a, b)} for a, b in ((0, 29), (0, 30), (10, 45), (5, 5))],
            "downgrade": [{"limit": lim, "family": f, "result": E.downgrade(lim, f, conns)} for lim in (0, 1, 2, None, "own_units") for f in ("lynkpos", "lynkrewards")],
            "fit": [{"screen": [w, h], "design": [dw, dh], "result": E.fit(w, h, dw, dh)}
                    for w, h in ((390, 844), (1920, 1080), (1080, 1920), (800, 1280), (1366, 768), (240, 320), (3840, 2160))
                    for dw, dh in ((390, 844), (1280, 800), (1920, 1080), (400, 700))]}


def ts():
    return ("// Generated by tools/emulators_vectors.py from catalog/emulators.v1.json and services/billing.py. Do not edit.\n"
            'import type { EmulatorRegister } from "./emulators.js";\n'
            f"export const EMULATOR_REGISTER: EmulatorRegister = {json.dumps(register(), ensure_ascii=False, separators=(',', ':'))} as EmulatorRegister;\n")


def main(check=False):
    vec = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    bad = []
    for path, text in ((VEC, vec), (TS, ts())):
        if check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text: bad.append(path)
        else:
            open(path, "w", encoding="utf-8").write(text)
    if check and bad:
        print("out of date: " + ", ".join(bad) + " (run python3 tools/emulators_vectors.py)"); return 1
    if not check: print("wrote", VEC, "and", TS)
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
