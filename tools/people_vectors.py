#!/usr/bin/env python3
"""Shared vectors for LynkAttend, LynkQueue and LynkSurvey (NEW UPDATE 4, master blueprint section 63): cases run through the Python
reference (core/attendance.py, core/queue_tickets.py, core/surveys.py); the TypeScript ports (ts/src/attendance.ts, ts/src/queue.ts,
ts/src/survey.ts) must give the same answers.
  python3 tools/people_vectors.py          writes contract/vectors/people.v1.json
  python3 tools/people_vectors.py --check  fails when the file is out of date (tests/test_people_rules.py)"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import attendance as A, queue_tickets as Q, surveys as S  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "people.v1.json")
IDS = ["123456789", "A6F87399", "2456HYOE99", "R4279", "DYY87HIO", "AB1", "P-00-12", "NIN 1985 0412 3301", "", "0000"]
PINS = ["111111", "123456", "654321", "121212", "123123", "482915", "908172", "12345", "abcdef", "135790"]
DOORS = [("face_idcn", ["ok"], []), ("face_idcn", ["fail", "fail", "fail", "ok"], []), ("face_finger_idcn", ["fail", "fail", "fail", "ok"], []),
         ("face_finger_idcn", ["ok"], ["face"]), ("finger_idcn", ["fail"] * 3 + ["fail"] * 5, []), ("idcn", ["fail", "ok"], []),
         ("face_finger_idcn", [], ["face", "finger"]), ("face_idcn", ["fail"], [])]
CODES = [0, 1, 31, 32, 999_999, 1_000_000_000 - 1, Q.CAPACITY - 1]
AFTER = [None, "22222Z", "A2K9P2", "FUCKZZ", "ZZZZZY"]
WAITING = [{"id": "a", "seq": 1}, {"id": "b", "seq": 2, "priority": True}, {"id": "c", "seq": 3}, {"id": "d", "seq": 4, "appointment": 600},
           {"id": "e", "seq": 5, "held": True}]
PICKS = [(0, 500), (3, 500), (0, 595), (5, 700)]


def build():
    return {
        "description": "LynkAttend, LynkQueue and LynkSurvey rule vectors (core/attendance.py, core/queue_tickets.py and core/surveys.py are the "
                       "reference; the TypeScript ports must agree). Generated by tools/people_vectors.py.",
        "attendance": {
            "idcn": [{"id": i, "idcn": A.idcn(i)} for i in IDS],
            "easy_pin": [{"pin": p, "easy": A.is_easy_pin(p)} for p in PINS],
            "pin_group_size": A.PIN_GROUP_SIZE, "easy_pin_count": A.EASY_PIN_COUNT,
            "means": {s: A.means_of(s) for s in A.SETS},
            "sets_allowed": [{"face": f, "finger": g, "sets": A.sets_allowed(f, g)} for f in (True, False) for g in (True, False)],
            "door": [{"set": s, "attempts": a, "broken": b, "out": A.door(s, a, b)} for s, a, b in DOORS],
            "checkers": {"list": ["ama", "ben", "chi"], "me": "ben", "choices": A.checker_choices(["ama", "ben", "chi"], "ben")},
            "warning": [{"used": u, "warn": A.pin_group_warning(u)} for u in (0, 899_009, 899_010, A.PIN_GROUP_SIZE)],
            "no_check_out": [{"in": i, "end": e, "due": A.no_check_out_due(i, e)} for i, e in ((480, 1020), (480, None), (1200, 1380), (1320, 300))],
        },
        "queue": {
            "alphabet": Q.ALPHABET, "capacity": Q.CAPACITY,
            "codes": [{"n": n, "code": Q.code(n)} for n in CODES],
            "next": [{"after": a, "next": Q.next_code(a)} for a in AFTER],
            "sections": [{"s": s, "valid": Q.valid_section(s)} for s in ("LAB", "PHA", "AD1", "lab", "KKK", "ADMS", "SEX")],
            "block": Q.reserve_block("A2K9P2"),
            "pick": [{"served_since_priority": s, "now": n, "next": Q.pick_next(WAITING, s, n)} for s, n in PICKS], "waiting": WAITING,
            "wait": [{"place": p, "avg": a, "open": o, "minutes": Q.wait_minutes(p, a, o)} for p, a, o in ((8, 6, 2), (1, 4, 3), (5, 5, 0))],
            "put_back": [{"order": ["a", "b", "c", "d", "e"], "ticket": "a", "missed": 100, "now": n, "out": Q.put_back(["a", "b", "c", "d", "e"], "a", 100, n)} for n in (110, 116)],
            "running_late": {"order": ["a", "b", "c", "d"], "ticket": "b", "out": Q.running_late(["a", "b", "c", "d"], "b")},
        },
        "survey": {
            "sample": [{"margin": m, "population": p, "n": S.sample_size(m, p)} for m, p in ((5, None), (3, None), (5, 1000), (10, None), (1, 100000))],
            "margin": [{"share": s, "answers": n, "tenths": S.margin(s, n)} for s, n in ((54, 600), (50, 100), (10, 2000), (50, 0))],
            "show": [{"size": n, "show": S.can_show(n)} for n in (0, 4, 5, 12)],
            "may_answer": [{"rule": r, "already": a, "invite": i, "signed_in": g, "phone": p, "out": S.may_answer(r, a, i, g, p)}
                           for r, a, i, g, p in (("open", False, False, False, False), ("open", True, False, False, False), ("one_per_phone", False, False, False, False),
                                                 ("one_per_phone", False, False, False, True), ("invited", False, False, False, False), ("verified", False, False, True, False))],
            "flags": [{"seconds": s, "questions": q, "same": m, "today": t, "shared": d, "out": S.real_answer_flags(s, q, m, t, d)}
                      for s, q, m, t, d in ((5, 5, False, 1, False), (60, 5, True, 1, False), (60, 5, False, 9, False), (60, 5, False, 90, True))],
            "groups": [{"group": g, "counts": {"women": 50}, "targets": {"women": 50, "men": 50}, "open": S.group_open(g, {"women": 50}, {"women": 50, "men": 50})} for g in ("women", "men", "other")],
        },
    }


def main(check=False):
    text = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    if check:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text: print(f"out of date: {OUT} (run python3 tools/people_vectors.py)"); return 1
        return 0
    open(OUT, "w", encoding="utf-8").write(text); print("wrote", OUT); return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
