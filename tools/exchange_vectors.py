#!/usr/bin/env python3
"""Shared vectors for LynkExchange's price and book-value rules (EXCHANGE UPDATE, master blueprint 65): core/exchange.py is the
reference and ts/src/exchange.ts must agree. Also writes ts/src/exchange.generated.ts with the locked levels and tier parts.
  python3 tools/exchange_vectors.py          writes contract/vectors/exchange.v1.json and ts/src/exchange.generated.ts
  python3 tools/exchange_vectors.py --check  fails when either file is out of date (tests/test_exchange_office.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import exchange as X  # noqa: E402
from services import billing as B  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "exchange.v1.json")
TS = os.path.join(ROOT, "ts", "src", "exchange.generated.ts")
LEVELS = [list(x) for x in B.EXCHANGE_LEVELS]
TIERS = [dict(B.FEATURES["lynkexchange"][0])]
for t in B.FEATURES["lynkexchange"][1:]:
    TIERS.append({**TIERS[-1], **t})
TIER_BPS = [t["lynkomni_part_bps"] for t in TIERS]


def _try(f, *a):
    try:
        return {"value": f(*a)}
    except ValueError:
        return {"error": True}


def build():
    vols = [0, 99999, 100000, 999999, 1000000, 9999999, 10000000, 10 ** 12, -1]
    quotes = [(100000, 61, 100, 50), (100000, 1300, 1, 50), (12345, 7, 3, 20), (1, 1, 1, 0), (99, 1, 1, 50), (100000, 1, 1, 10000),
              (0, 1, 1, 50), (100, 0, 1, 50), (100, 1, 1, 1.5), (5000000, 11, 10, 40)]
    mids = [(100000, 60695, 61, 100), (100000, 61000, 61, 100), (100000, 61500, 61, 100), (1, 0, 0, 1), (5000000, 5478000, 11, 10)]
    costs = [(1000, 700, 1000), (1000, 700, 333), (1000, 700, 1), (3, 10, 1), (1000, 700, 0), (1000, 700, 1001)]
    return {
        "version": 1, "description": "LynkExchange's price and book-value rules (EXCHANGE UPDATE 65). core/exchange.py is the reference.",
        "levels": [{"v": v, "expect": _try(X.level_bps, B.EXCHANGE_LEVELS, v)} for v in vols],
        "part": [{"t": t, "v": v, "expect": _try(X.part_bps, t, B.EXCHANGE_LEVELS, v)} for t in TIER_BPS for v in (0, 100000, 10000000)],
        "quote": [{"a": q, "expect": _try(X.quote, *q)} for q in quotes],
        "mid": [{"a": m, "expect": _try(X.above_mid_bps, *m)} for m in mids],
        "cost": [{"a": c, "expect": _try(X.cost_out, *c)} for c in costs],
    }


def ts_source():
    return ("// GENERATED by tools/exchange_vectors.py from services/billing.py (locked prices). Do not edit by hand.\n"
            "import type { Levels } from \"./exchange.js\";\n"
            f"export const LEVELS: Levels = {json.dumps(LEVELS)};\n"
            f"export const TIER_PART_BPS: readonly number[] = {json.dumps(TIER_BPS)};\n")


def main():
    vec = json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"
    ts = ts_source()
    if "--check" in sys.argv:
        stale = [p for p, want in ((OUT, vec), (TS, ts)) if not os.path.exists(p) or open(p, encoding="utf-8").read() != want]
        if stale:
            print("out of date:", ", ".join(os.path.relpath(p, ROOT) for p in stale), "- run python3 tools/exchange_vectors.py")
            sys.exit(1)
        return
    for p, text in ((OUT, vec), (TS, ts)):
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT), "and", os.path.relpath(TS, ROOT))


if __name__ == "__main__":
    main()
