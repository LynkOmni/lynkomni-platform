#!/usr/bin/env python3
"""Writes what the other languages need for the shared username check (Step 0, blueprint 44 B):
  * contract/vectors/usernames.v1.json: the reserved words as the Python reference computed them (rule words + product,
    brand, host and partner names) and test cases with the reason the reference gives, so every port must agree;
  * ts/src/usernames.generated.ts: the same data for the TypeScript port (never hand-edited).
Run after changing the rule, the catalog or the provider ledger:  python3 tools/usernames_generate.py  (add --check in tests)."""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import usernames as u  # noqa: E402

CASES = ["mamas.kitchen", "@MAMAS.KITCHEN", "Mama", "grace_salon_2", "the.corner.shop", "support_1", "a.b", "abc",
         "", ".abc", "abc.", "a..b", "ab", "a" * 31, "mamas-kitchen", "mamás", "mama kitchen", "mamas.com", "joe.rw", "shop.io",
         "lynkomni", "lynk_omni", "l.y.n.k.o.m.n.i", "cruxomni", "lynkpos", "pos", "admin", "support", "safety", "partners", "shop",
         "mtn", "m.pesa", "airtel", "google", "kra",
         "adm1n", "5upport", "lynk0mni", "lynkp0s", "m0bile", "rn.pesa"]


def build():
    vectors = {
        "description": "Shared vectors for the username rule (contract/usernames.v1.json). `reserved` is the full reserved list the Python reference computed from the rule, the product catalog, the address hosts and the provider ledger; `cases` give the reference's verdict and reason. Generated by tools/usernames_generate.py.",
        "rule": "contract/usernames.v1.json",
        "reserved": sorted(u.RESERVED),
        "cases": [{"input": c, **{k: v for k, v in u.check(c).items() if k != "looks_like"}} for c in CASES],
    }
    ts = ("// Generated by tools/usernames_generate.py from contract/usernames.v1.json, the catalog and the provider ledger. Never hand-edit.\n"
          f"export const USERNAME_RULE = {json.dumps({k: u.RULE[k] for k in ('min', 'max', 'pattern', 'reserved_endings', 'look_alike_map')}, ensure_ascii=False)} as const;\n"
          f"export const RESERVED: ReadonlySet<string> = new Set({json.dumps(sorted(u.RESERVED))});\n")
    return vectors, ts


def main(check=False):
    vectors, ts = build()
    outs = {os.path.join(ROOT, "contract", "vectors", "usernames.v1.json"): json.dumps(vectors, indent=1, ensure_ascii=False) + "\n",
            os.path.join(ROOT, "ts", "src", "usernames.generated.ts"): ts}
    stale = []
    for path, text in outs.items():
        if check:
            if not os.path.isfile(path) or open(path, encoding="utf-8").read() != text:
                stale.append(os.path.relpath(path, ROOT))
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    if check and stale:
        print("stale:", ", ".join(stale)); sys.exit(1)
    print("username vectors and TypeScript data are up to date" if check else f"wrote {len(outs)} files ({len(vectors['reserved'])} reserved words, {len(vectors['cases'])} cases)")


if __name__ == "__main__":
    main("--check" in sys.argv)
