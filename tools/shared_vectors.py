#!/usr/bin/env python3
"""Shared vectors for the parts every service shares (CONNECT UPDATE 71.3; section 4 row 71.9 step 2): core/shared.py is the
reference and ts/src/shared.ts must agree. Also writes ts/src/shared.generated.ts with the register.
  python3 tools/shared_vectors.py          writes contract/vectors/shared.v1.json and ts/src/shared.generated.ts
  python3 tools/shared_vectors.py --check  fails when either file is out of date (tests/test_shared.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import shared as SH, build_sections as BS  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "shared.v1.json")
TS = os.path.join(ROOT, "ts", "src", "shared.generated.ts")


def _try(f, *a):
    try:
        return {"value": f(*a)}
    except KeyError:
        return {"error": True}


def build():
    roles = [(k, r) for k in ("device", "account_deputy", "base", "nope") for r in ("owner", "manager", "cashier", "rider", "deputy", "accountant", "chef")]
    may = [(k, r, area, perm) for k, r in (("device", "cashier"), ("device", "manager"), ("base", "accountant"), ("base", "auditor"))
           for area in ("pos", "acc", "crm") for perm in ("view", "approve", "post")]
    built = {s: (BS.status(s) in ("locked", "building") or str(s) == "4") for s in sorted({x["build_section"] for x in SH.SHARED["calendar"]["sources"]})}
    return {"version": 1, "description": "The shared parts (CONNECT UPDATE 71.3). core/shared.py is the reference.",
            "base_role": [{"a": [k, r], "expect": _try(SH.base_role, k, r)} for k, r in roles],
            "may": [{"a": list(x), "expect": _try(SH.may, *x)} for x in may],
            "binnable": [{"a": k, "expect": SH.binnable(k)} for k in ("crm_record", "file", "invoice", "ballot", "journal")],
            "purge_due": [{"a": [a, n], "expect": SH.purge_due(a, n)} for a, n in ((0, 0), (0, 29 * 86400), (0, 30 * 86400), (100, 30 * 86400 + 99))],
            "may_audit": [{"a": r, "expect": SH.may_audit(r)} for r in ("owner", "auditor", "accountant", "manager", "staff")],
            "built": built, "calendar_sources": [x["id"] for x in SH.calendar_sources(lambda s: built[s])],
            "settle": [{"a": [k, a, b], "expect": _settle(k, a, b)} for k, a, b in SETTLE_CASES]}


def _ch(device, hlc, accepted, **fields):
    return {"device": device, "hlc": hlc, "accepted": accepted, "fields": fields}


# Two offline changes to one record (CONNECT UPDATE 71.3): every rule, ties on the clock settled by the device id.
SETTLE_CASES = [
    ("sale", _ch("d1", 5, 2, total=100), _ch("d2", 6, 1, total=200)),
    ("voucher_redeem", _ch("d1", 5, 2), _ch("d2", 1, 1)), ("voucher_redeem", _ch("d2", 5, 3), _ch("d1", 9, 3)),
    ("product", _ch("d1", 5, 2, name="A", price_minor=100), _ch("d2", 7, 1, price_minor=120, colour="red")),
    ("product", _ch("d2", 7, 2, name="B"), _ch("d1", 7, 1, name="C")), ("customer_record", _ch("d1", 3, 1, note="x"), _ch("d2", 2, 2, note="x")),
    ("deal", _ch("d1", 1, 1, role="lead"), _ch("d2", 2, 2, stage="won")),
    ("contact_consent", _ch("d1", 9, 2, state="given"), _ch("d2", 1, 1, state="withdrawn")), ("card_freeze", _ch("d1", 1, 1, state="frozen"), _ch("d2", 2, 2, state="frozen")),
    ("device_lock", _ch("d1", 1, 1, state="unlocked"), _ch("d2", 2, 2, state="locked")),
    ("provider_payment", _ch("d1", 1, 1), _ch("d2", 2, 2)), ("unknown_kind", _ch("d1", 1, 1), _ch("d2", 2, 2)),
]


def _settle(k, a, b):
    try:
        return {"value": SH.settle(k, a, b)}
    except (KeyError, ValueError):
        return {"error": True}


def ts_source():
    data = {"roles": SH.SHARED["roles"], "base": SH.BASE_ROLES, "calendar": SH.SHARED["calendar"]["sources"],
            "bin": {"keep_days": SH.SHARED["recycle_bin"]["keep_days"], "kinds": SH.SHARED["recycle_bin"]["kinds"]},
            "audit_roles": SH.SHARED["timeline"]["audit_roles"], "address_kinds": SH.SHARED["address_book"]["kinds"],
            "clash": {f: SH.SHARED["offline_clash"][f] for f in ("kinds", "safest", "flag_fields")}}
    return ("// GENERATED by tools/shared_vectors.py from catalog/shared.v1.json and catalog/enterprise.v1.json. Do not edit by hand.\n"
            f"export const SHARED = {json.dumps(data)} as const;\n")


def main():
    vec = json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"
    ts = ts_source()
    if "--check" in sys.argv:
        stale = [p for p, want in ((OUT, vec), (TS, ts)) if not os.path.exists(p) or open(p, encoding="utf-8").read() != want]
        if stale:
            print("out of date:", ", ".join(os.path.relpath(p, ROOT) for p in stale), "- run python3 tools/shared_vectors.py")
            sys.exit(1)
        return
    for p, text in ((OUT, vec), (TS, ts)):
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT), "and", os.path.relpath(TS, ROOT))


if __name__ == "__main__":
    main()
