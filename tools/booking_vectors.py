#!/usr/bin/env python3
"""Shared vectors for LynkBooking's money and figures (BOOKING UPDATE, master blueprint 64): core/booking.py is the reference and
ts/src/booking.ts must agree. Also writes ts/src/booking.generated.ts with the locked commission rule from services/billing.py.
  python3 tools/booking_vectors.py          writes contract/vectors/booking.v1.json and ts/src/booking.generated.ts
  python3 tools/booking_vectors.py --check  fails when either file is out of date (tests/test_booking_office.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import booking as K  # noqa: E402
from services.billing import BOOKING_COMMISSION as R  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "booking.v1.json")
TS = os.path.join(ROOT, "ts", "src", "booking.generated.ts")


def _try(f, *a):
    try:
        return {"value": f(*a)}
    except ValueError:
        return {"error": True}


def build():
    cases = []
    for kind in K.KINDS + ("flight",):
        for source in ("lynkbooking", "returning", "partner"):
            for amount, first, guests, tickets in ((12345, True, 0, 0), (12345, False, 0, 0), (150000, True, 4, 3), (0, False, 2, 0), (-5, False, 0, 0)):
                cases.append({"k": kind, "s": source, "a": amount, "f": first, "g": guests, "t": tickets,
                              "expect": _try(K.commission, R, kind, source, amount, first, guests, tickets)})
    cases.append({"k": "appointment", "s": "lynkbooking", "a": 50000, "f": True, "g": 0, "t": 0, "fixed": {"cap": 6000},
                  "expect": _try(lambda: K.commission(R, "appointment", "lynkbooking", 50000, True, fixed={"cap": 6000}))})
    week = [{"weekday": w, "hour": h} for w, h in ((0, 9), (0, 9), (0, 10), (4, 18), (4, 18), (4, 18), (6, 23))]
    return {
        "version": 1, "description": "LynkBooking's commission and figures (BOOKING UPDATE 64). core/booking.py is the reference.",
        "commission": cases,
        "forecast": [{"b": b, "w": w, "expect": _try(K.busy_forecast, b, w)} for b, w in ((week, 1), (week, 2), (week, 3), ([], 4), (week, 0), ([{"weekday": 7, "hour": 1}], 1))],
        "empty": [{"c": c, "b": b, "expect": K.empty_hours(c, b)} for c, b in (({"0-9": 3, "0-10": 3, "4-18": 2}, {"0-9": 3, "4-18": 1}), ({"1-8": 5}, {"1-8": 7}), ({}, {}))],
        "noshow": [{"c": c, "n": n, "expect": _try(K.no_show_rate, c, n)} for c, n in ((0, 0), (40, 3), (3, 1), (7, 7), (5, 6))],
    }


def ts_source():
    return ("// GENERATED by tools/booking_vectors.py from services/billing.py BOOKING_COMMISSION (locked prices). Do not edit by hand.\n"
            "import type { CommissionRules } from \"./booking.js\";\n"
            f"export const COMMISSION: CommissionRules = {json.dumps(R, separators=(',', ':'))};\n")


def main():
    vec = json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"
    ts = ts_source()
    if "--check" in sys.argv:
        stale = [p for p, want in ((OUT, vec), (TS, ts)) if not os.path.exists(p) or open(p, encoding="utf-8").read() != want]
        if stale:
            print("out of date:", ", ".join(os.path.relpath(p, ROOT) for p in stale), "- run python3 tools/booking_vectors.py")
            sys.exit(1)
        return
    for p, text in ((OUT, vec), (TS, ts)):
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT), "and", os.path.relpath(TS, ROOT))


if __name__ == "__main__":
    main()
