#!/usr/bin/env python3
"""Shared vectors for the device-side ad rules (ADS UPDATE, master blueprint 79; section 4 row 79.10): services/ads.py may_show and
counts are the reference and ts/src/ads.ts must agree. Also writes ts/src/ads.generated.ts with the register's places and rules.
  python3 tools/ads_vectors.py          writes contract/vectors/ads.v1.json and ts/src/ads.generated.ts
  python3 tools/ads_vectors.py --check  fails when either file is out of date (tests/test_ads_screens.py)"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from services import ads as A  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "ads.v1.json")
TS = os.path.join(ROOT, "ts", "src", "ads.generated.ts")


def _try(f, **kw):
    try:
        return {"value": f(**kw)}
    except ValueError:
        return {"error": True}


def build():
    cases = []
    for place in ("pos_idle", "pos_after_sale", "receipt_footer", "dashboard_card", "nowhere"):
        for screen in (None, "payment", "settings", "receipt"):
            for kw in ({}, {"country_on": True}, {"country_on": True, "hosting": True}, {"country_on": True, "ad_free": True},
                       {"country_on": True, "lite": True}, {"country_on": True, "workspace": "household"}, {"country_on": True, "workspace": "school"},
                       {"country_on": True, "audience": "child", "hosting": True}):
                a = {"place": place, "screen": screen, **kw}
                cases.append({"a": a, "expect": _try(A.may_show, **a)})
    seen = [(50, 1000), (49, 5000), (100, 999), (None, None), (75, 1200)]
    return {"version": 1, "description": "Device-side ad rules (ADS UPDATE 79). services/ads.py is the reference.",
            "may_show": cases, "counts": [{"a": list(v), "expect": A.counts(*v)} for v in seen]}


def ts_source():
    R = A.REGISTER
    data = {"places": sorted(A.SURFACES), "never": R["never"], "never_audiences": R["never_audiences"], "hosted_by_choice": sorted(A.HOSTED_BY_CHOICE),
            "min_visible_pct": R["viewability"]["min_visible_pct"], "min_visible_ms": R["viewability"]["min_visible_ms"],
            "share_bps": {k: p["share_bps"] for k, p in sorted(A.PLACES.items())}}
    return ("// GENERATED by tools/ads_vectors.py from catalog/ads.v1.json. Do not edit by hand.\n"
            f"export const ADS = {json.dumps(data)} as const;\n")


def main():
    vec = json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"
    ts = ts_source()
    if "--check" in sys.argv:
        stale = [p for p, want in ((OUT, vec), (TS, ts)) if not os.path.exists(p) or open(p, encoding="utf-8").read() != want]
        if stale:
            print("out of date:", ", ".join(os.path.relpath(p, ROOT) for p in stale), "- run python3 tools/ads_vectors.py")
            sys.exit(1)
        return
    for p, text in ((OUT, vec), (TS, ts)):
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT), "and", os.path.relpath(TS, ROOT))


if __name__ == "__main__":
    main()
