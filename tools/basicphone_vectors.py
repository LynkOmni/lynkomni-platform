#!/usr/bin/env python3
"""Shared vectors for sign-up, sign-in, help and notifications on basic phones (MASTER UPDATE; build section 3): scripted
sessions run through the Python reference (identity/basic_phone.py); the TypeScript port (ts/src/basicphone.ts) must give the
same pages, ends and actions.
  python3 tools/basicphone_vectors.py          writes contract/vectors/basicphone.v1.json
  python3 tools/basicphone_vectors.py --check  fails when the file is out of date (tests/test_basic_phone.py)"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from identity import basic_phone as B  # noqa: E402
from core import usernames as U  # noqa: E402

OUT = os.path.join(ROOT, "contract", "vectors", "basicphone.v1.json")
CTX = {"age": 18, "lines": [["n1", "New sign-in on your account"], ["n2", "Low stock: Rice 1 kg"], ["n3", "Your day is closed"]], "recovery": "7F3K-9Q2M-X81B-4TZC", "case": "LOCASE-2101-7710-0042"}
PIN = "4719"
TAKEN = ["mamas.kitchen"]
SESSIONS = [
    ["1", "4719", "1", "2", "0", "0", "2", "1", "3", "0", "0", "0", "0"],
    ["1", "1111", "1111", "4719"],
    ["1", "LOCKED"],
    ["2", "2"],
    ["2", "1", "Mamas.Kitchen", "a", "ama..shop", "@Ama.Shop", "1234", "4826", "4827", "4826", "4826", "1"],
    ["2", "1", "grace.k", "5813", "5813", "0", "3", "4"],
    ["3", "2", "0", "3"],
    ["9", "x", "0"],
]
TEXTS = [["New sign-in on your account", None], ["Low stock: Rice 1 kg", "LOSTK-1100-2200-3302"]]


def pin_check(t):
    if t == "LOCKED":
        return "locked"
    return "ok" if t == PIN else ("wrong", 9)


def username_check(u):
    r = U.check(u)
    return None if r["ok"] else r["reason"]


def build():
    ctx = dict(CTX, pin_check=pin_check, username_check=username_check, taken=lambda u: u in TAKEN)
    sessions = []
    for inputs in SESSIONS:
        st, steps = B.start(), []
        steps.append({"input": None, "page": B.page(st, CTX), "ends": False, "action": None})
        for x in inputs:
            st, ends, action = B.step(st, x, ctx)
            steps.append({"input": x, "screen": st["screen"], "page": B.page(st, CTX), "ends": ends, "action": action})
            if ends:
                break
        sessions.append(steps)
    usernames = sorted({x.lower().lstrip("@") for s in SESSIONS for x in s if not x.isdigit()})
    return {"description": "Basic-phone account vectors (identity/basic_phone.py is the reference; ts/src/basicphone.ts must agree). Generated by tools/basicphone_vectors.py.",
            "ctx": CTX, "pin": PIN, "taken": TAKEN, "sessions": sessions,
            "username_checks": {u: username_check(u) for u in usernames},
            "texts": [{"title": t, "record": r, "text": B.text_notification(t, r)} for t, r in TEXTS]}


def main(check=False):
    text = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    if check:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print(f"out of date: {OUT} (run python3 tools/basicphone_vectors.py)"); return 1
        print("basic-phone vectors are current"); return 0
    open(OUT, "w", encoding="utf-8").write(text); print("wrote", OUT); return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
