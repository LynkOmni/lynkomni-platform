"""Writes catalog/data-dictionary.v1.json (CONNECT UPDATE 71.3, section 4 row 71.9): every record type with its public id prefix
(core/ids.py) and every event of the newest contract with who may write it and its fields. Personal data never sits in a record or
an event: it lives only in the PII vault, by reference. Run after a change to the id registry or the contract; --check fails when
the file is stale."""
import glob, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from core import ids

OUT = os.path.join(ROOT, "catalog", "data-dictionary.v1.json")


def build():
    latest = max(glob.glob(os.path.join(ROOT, "contract", "event-payloads.v*.json")), key=lambda p: int(re.search(r"v(\d+)", p).group(1)))
    con = json.load(open(latest, encoding="utf-8")); ev = con.get("events", con)
    version = int(re.search(r"v(\d+)", latest).group(1))
    return {
        "version": 1,
        "note": "Generated by tools/data_dictionary.py from core/ids.py and the newest contract; never edit by hand.",
        "contract_version": version,
        "personal_data": "Names, contact details, ID numbers and positions live only in the PII vault, by reference; no record field or event field below holds them.",
        "records": [{"code": t["code"], "prefix": t["prefix"], "name": t["name"], "purpose": t["purpose"]} for t in sorted(ids.TYPES.values(), key=lambda t: t["code"])],
        "events": [{"type": n, "written_by": sorted(e["origins"]), "fields": sorted(e["payload"].get("properties", {})), "required": sorted(e["payload"].get("required", []))}
                   for n, e in sorted(ev.items())],
    }


def main():
    text = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("data dictionary is current" if ok else "data dictionary is stale: run python3 tools/data_dictionary.py")
        sys.exit(0 if ok else 1)
    open(OUT, "w", encoding="utf-8").write(text); print("wrote", OUT)


if __name__ == "__main__":
    main()
